def generate_repository_hash(root: Path, sizes: dict[str, int]) -> str:
    digest = hashlib.sha256()
    for size_name, count in sizes.items():
        for index in range(count):
            relative = Path(size_name) / f"case_{index:06d}.ts"
            digest.update(relative.as_posix().encode("utf-8") + b"\0" + (root / relative).read_bytes())
    rule = (root / "scan-rule.yml").read_bytes()
    digest.update(b"scan-rule.yml\0" + rule)
    return digest.hexdigest()


