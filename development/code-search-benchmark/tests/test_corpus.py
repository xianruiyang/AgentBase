from __future__ import annotations

import importlib.util
import io
import json
import sys
import tempfile
import unittest
from contextlib import redirect_stderr
from pathlib import Path
from unittest import mock


MODULE_PATH = Path(__file__).resolve().parents[1] / "corpus" / "validate_corpus.py"
SPEC = importlib.util.spec_from_file_location("validate_corpus", MODULE_PATH)
assert SPEC and SPEC.loader
MODULE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(MODULE)


class CorpusValidationTests(unittest.TestCase):
    def test_synthetic_corpus_reports_stable_counts_without_repository_data(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            source = root / "source.py"
            source.write_text("value = 1\n", encoding="utf-8")
            corpus = root / "corpus.json"
            corpus.write_text(json.dumps({
                "schema": MODULE.SCHEMA,
                "version": "2099-01-01.1",
                "created_utc": "2099-01-01T00:00:00Z",
                "workspace_roles": {"synthetic": {"description": "generated by the test"}},
                "cases": [{
                    "id": "synthetic-location",
                    "workspace_role": "synthetic",
                    "prompt": "Locate the generated value.",
                    "answer_contract": {"required": ["source path"]},
                    "oracle": {
                        "kind": "source-relation",
                        "source": {"path": "source.py", "sha256": MODULE.digest(source)},
                    },
                }],
            }), encoding="utf-8")

            result = MODULE.validate(corpus, {"synthetic": root})

            self.assertEqual({
                "ok": True,
                "case_count": 1,
                "validated_case_count": 1,
                "failures": [],
            }, result)

    def test_stale_source_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            source = root / "source.txt"
            source.write_text("current", encoding="utf-8")
            corpus = root / "corpus.json"
            corpus.write_text(json.dumps({
                "schema": MODULE.SCHEMA,
                "cases": [{
                    "id": "stale",
                    "workspace_role": "agentbase",
                    "prompt": "find source",
                    "answer_contract": {"required": ["source"]},
                    "oracle": {"kind": "source-relation", "source": {"path": "source.txt", "sha256": "0" * 64}},
                }],
            }), encoding="utf-8")
            result = MODULE.validate(corpus, {"agentbase": root})
            self.assertFalse(result["ok"])
            self.assertIn("stale source", result["failures"][0])

    def test_selected_case_accepts_arbitrary_workspace_role(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            selected_root = root / "selected"
            selected_root.mkdir()
            source = selected_root / "source.ts"
            source.write_text("const current = true;", encoding="utf-8")
            corpus = root / "corpus.json"
            corpus.write_text(json.dumps({
                "schema": MODULE.SCHEMA,
                "cases": [
                    {
                        "id": "selected",
                        "workspace_role": "typescript-project",
                        "prompt": "find source",
                        "answer_contract": {"required": ["source"]},
                        "oracle": {
                            "kind": "source-relation",
                            "source": {"path": "source.ts", "sha256": MODULE.digest(source)},
                        },
                    },
                    {
                        "id": "unselected",
                        "workspace_role": "unavailable-project",
                        "prompt": "find source",
                        "answer_contract": {"required": ["source"]},
                        "oracle": {
                            "kind": "source-relation",
                            "source": {"path": "missing.cpp", "sha256": "0" * 64},
                        },
                    },
                ],
            }), encoding="utf-8")

            result = MODULE.validate(
                corpus,
                {"typescript-project": selected_root},
                {"selected"},
            )

            self.assertTrue(result["ok"])
            self.assertEqual(result["case_count"], 2)
            self.assertEqual(result["validated_case_count"], 1)

    def test_selected_case_requires_a_bounded_answer_contract(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            source = root / "source.cpp"
            source.write_text("int value;", encoding="utf-8")
            corpus = root / "corpus.json"
            corpus.write_text(json.dumps({
                "schema": MODULE.SCHEMA,
                "cases": [{
                    "id": "invalid-contract",
                    "workspace_role": "cpp-project",
                    "prompt": "",
                    "answer_contract": {"required": []},
                    "oracle": {
                        "kind": "source-relation",
                        "source": {"path": "source.cpp", "sha256": MODULE.digest(source)},
                        "semantic_boundary": [],
                    },
                }],
            }), encoding="utf-8")

            result = MODULE.validate(corpus, {"cpp-project": root})

            self.assertFalse(result["ok"])
            self.assertEqual(len(result["failures"]), 3)

    def test_workspace_argument_parser_rejects_duplicates(self) -> None:
        with self.assertRaisesRegex(ValueError, "duplicate workspace role"):
            MODULE.parse_workspaces(["project=C:\\one", "project=C:\\two"])

    def test_cli_explains_how_to_restore_a_missing_local_corpus(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            missing = Path(temp) / "private-corpus.json"
            stderr = io.StringIO()
            with mock.patch.object(sys, "argv", ["validate_corpus.py", str(missing), "--workspace", f"test={temp}"]):
                with redirect_stderr(stderr), self.assertRaises(SystemExit) as raised:
                    MODULE.main()
            self.assertEqual(2, raised.exception.code)
            self.assertIn("restore it on this host", stderr.getvalue())


if __name__ == "__main__":
    unittest.main()
